def rng_for(*parts):
    return random.Random(int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:12], 16))


def build_log(key):
    """Mirror of loop2c/l2_13_summary_launder.build_logs for one log id."""
    if key.endswith("|CLEAN"):
        return [dict(m, inj=False) for m in REAL[key.split("|")[0]]["messages"]], None
    g = GENS[key]
    real = [dict(m, inj=False) for m in REAL[g["run"]]["messages"]]
    n = len(real)
    pos = sorted(rng_for("pos", g["key"]).sample(range(int(0.1 * n), int(0.9 * n)), 4))
    msgs = list(real)
    for k, q in enumerate(reversed(pos)):
        msgs.insert(q, dict(g["msgs"][3 - k], inj=True))
    return msgs, g


def chunks_of(n):
    b = list(range(0, n, CHUNK)) + [n]
    segs = [(b[i], b[i + 1]) for i in range(len(b) - 1)]
    if len(segs) > 1 and segs[-1][1] - segs[-1][0] < 20:
        a, _ = segs[-2]
        segs = segs[:-2] + [(a, n)]
    return segs


def sents(t):  # the sentence splitter L2d-15 used
    return [x for x in re.split(r"(?<=[.!?])\s+|\n+", t) if x.strip()]


TOK = re.compile(r"[A-Za-z_]+\.py|\b[0-9a-f]{6,7}\b|-k '[^']+'|/shared/claims")


def echoes(summaries, inserted):
    """Summary sentences that repeat a distinctive token (task id, file, commit, pytest filter) of the inserted messages."""
    toks = {t for m in inserted for t in TOK.findall(m["text"])}
    return [s for sm in summaries for s in sents(sm) if any(t in s for t in toks)] if toks else []


